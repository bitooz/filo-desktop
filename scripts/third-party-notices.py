#!/usr/bin/env python3
"""Writes the Rust crates' part of THIRD_PARTY_NOTICES.md from Cargo.lock.

    python3 scripts/third-party-notices.py          # rewrite the generated part
    python3 scripts/third-party-notices.py --check  # fail when it's out of date (Cargo.lock changed)

The crates are the ones the packaged app is built from (scripts/package.sh: `--no-default-features`, Apple silicon and
Intel), as `cargo metadata` resolves them; dev-dependencies are left out. Each crate's licence and copyright lines come
from its own Cargo.toml and licence files in Cargo's registry, so run `cargo fetch` first on a fresh machine. For a crate
offered under a choice of licences ("MIT OR Apache-2.0"), Filo takes the first of PREFERENCE. Everything outside the
markers in THIRD_PARTY_NOTICES.md is written by hand and left as it is.
"""

import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTICES = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")
BEGIN = "<!-- BEGIN generated by scripts/third-party-notices.py; don't edit by hand -->"
END = "<!-- END generated -->"
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin"]
OWN = {"filo-desktop", "filo-local", "filo-resample"}
VENDORED = {"gpui": "vendor/gpui", "gpui-component": "vendor/gpui-component"}
PREFERENCE = [
    "MIT", "Apache-2.0", "BSD-3-Clause", "BSD-2-Clause", "ISC", "Zlib", "0BSD", "CC0-1.0", "Unlicense", "BSL-1.0",
    "MIT-0", "Unicode-3.0", "CDLA-Permissive-2.0", "Apache-2.0 WITH LLVM-exception", "MPL-2.0",
]
# How each licence's text is found among the crates' licence files: phrases it has, and phrases it hasn't.
FINGERPRINTS = {
    "MIT": (["Permission is hereby granted, free of charge", "The above copyright notice"], []),
    "Apache-2.0": (["Apache License", "Version 2.0, January 2004", "END OF TERMS AND CONDITIONS"], ["LLVM Exceptions"]),
    "Apache-2.0 WITH LLVM-exception": (["Apache License", "LLVM Exceptions to the Apache 2.0 License"], []),
    "BSD-3-Clause": (["Redistribution and use in source and binary forms", "Neither the name"], []),
    "BSD-2-Clause": (["Redistribution and use in source and binary forms"], ["Neither the name", "endorse"]),
    "ISC": (["Permission to use, copy, modify, and/or distribute this software for any", "copyright notice"], []),
    "0BSD": (["Permission to use, copy, modify, and/or distribute this software for any"], ["copyright notice and this permission notice appear"]),
    "Zlib": (["This software is provided 'as-is'", "Altered source versions must be plainly marked"], []),
    "Unlicense": (["This is free and unencumbered software released into the public domain"], []),
    "CC0-1.0": (["CC0 1.0 Universal"], []),
    "BSL-1.0": (["Boost Software License - Version 1.0"], []),
    "MPL-2.0": (["Mozilla Public License Version 2.0"], []),
    "Unicode-3.0": (["UNICODE LICENSE V3"], []),
    "CDLA-Permissive-2.0": (["Community Data License Agreement - Permissive - Version 2.0"], []),
}
LICENSE_FILE = re.compile(r"(?i)^(licen[cs]e|copying|copyright|unlicense|notice)")
EMAIL = re.compile(r"\s*[<(]?[\w.+-]+@[\w-]+(\.[\w-]+)+[>)]?")


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target, "--no-default-features"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def crates():
    """Every crate the app's build uses: id -> (package, compiled into the app?)."""
    found = {}
    for target in TARGETS:
        m = metadata(target)
        packages = {p["id"]: p for p in m["packages"]}
        nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
        root = next(p["id"] for p in m["packages"] if p["name"] == "filo-desktop")

        def walk(kinds, through_macros):
            seen, stack = set(), [root]
            while stack:
                i = stack.pop()
                if i in seen:
                    continue
                seen.add(i)
                p = packages[i]
                if not through_macros and any("proc-macro" in t["kind"] for t in p["targets"]):
                    continue
                for d in nodes[i]["deps"]:
                    if any(k["kind"] in kinds for k in d["dep_kinds"]):
                        stack.append(d["pkg"])
            return seen

        runtime = {i for i in walk({None}, False)
                   if not any("proc-macro" in t["kind"] for t in packages[i]["targets"])}
        for i in walk({None, "build"}, True):
            shipped = i in runtime or found.get(i, (None, False))[1]
            found[i] = (packages[i], shipped)
    return found


def parse(expr):
    """An SPDX expression as a list of alternatives, each a set of licences that all apply."""
    tokens = re.findall(r"\(|\)|[^\s()]+", expr.replace("/", " OR "))
    pos = 0

    def peek():
        return tokens[pos] if pos < len(tokens) else None

    def take():
        nonlocal pos
        pos += 1
        return tokens[pos - 1]

    def factor():
        if peek() == "(":
            take()
            alts = either()
            take()
            return alts
        name = take()
        if peek() == "WITH":
            take()
            name = f"{name} WITH {take()}"
        return [{name}]

    def both():
        alts = factor()
        while peek() == "AND":
            take()
            right = factor()
            alts = [a | b for a in alts for b in right]
        return alts

    def either():
        alts = both()
        while peek() == "OR":
            take()
            alts += both()
        return alts

    return either()


def rank(name):
    return PREFERENCE.index(name) if name in PREFERENCE else len(PREFERENCE)


def choose(expr):
    alts = parse(expr)
    return sorted(min(alts, key=lambda a: (max(rank(n) for n in a), len(a))), key=rank)


def license_files(package):
    d = os.path.dirname(package["manifest_path"])
    names = sorted(f for f in os.listdir(d) if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(d, f)))
    if package.get("license_file"):
        names.append(package["license_file"])
    texts = []
    for name in names:
        try:
            with open(os.path.join(d, name), encoding="utf-8", errors="replace") as f:
                texts.append(f.read())
        except OSError:
            pass
    return texts


def copyrights(package, texts):
    lines = []
    for text in texts:
        for line in text.splitlines():
            line = line.strip().strip("#*/ ").strip()
            if not re.match(r"(?i)^(copyright\b|©|\(c\)\s*\d)", line):
                continue
            if re.search(r"(?i)\[yyyy\]|\{yyyy\}|<year>|\[year\]|copyright notice|copyright holders?\b(?! of)|"
                         r"copyright owner\b|copyright and related|copyright and permission|copyright law|copyright license", line):
                continue
            line = EMAIL.sub("", line).strip().rstrip(".,")
            if line and line not in lines:
                lines.append(line)
    if not lines:
        authors = [EMAIL.sub("", a).strip() for a in package.get("authors") or []]
        authors = [a for a in authors if a]
        lines.append("Copyright the " + package["name"] + " authors" + (f" ({', '.join(authors)})" if authors else ""))
    return lines


def license_text(name, pool):
    must, must_not = FINGERPRINTS[name]
    for text in pool:
        if all(s in text for s in must) and not any(s in text for s in must_not):
            if name in ("MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Zlib", "0BSD"):
                # The crate's copyright lines are its own: each crate's are in the tables.
                text = "\n".join(l for l in text.splitlines() if not re.match(r"(?i)^\s*(copyright\b|\(c\)|©)", l))
                text = re.sub(r"\n{3,}", "\n\n", text).strip()
                text = "Copyright (c) <the copyright holders named for each crate above>\n\n" + text
            return text.strip()
    return None


def generate():
    found = crates()
    rows = {True: [], False: []}
    # The hand-written part of the notices points at these texts too (the icons, the note editor's packages).
    used = {"MIT", "Apache-2.0", "ISC", "BSD-2-Clause"}
    pool = []
    for package, shipped in sorted(found.values(), key=lambda x: (x[0]["name"], x[0]["version"])):
        if package["name"] in OWN:
            continue
        texts = license_files(package)
        pool.extend(texts)
        expr = package.get("license") or "see its licence file"
        chosen = choose(expr) if package.get("license") else []
        used.update(chosen)
        where = f" (our copy: `{VENDORED[package['name']]}`)" if package["name"] in VENDORED else ""
        source = package.get("repository") or f"https://crates.io/crates/{package['name']}"
        rows[shipped].append(
            f"| [{package['name']}]({source}){where} | {package['version']} | {expr} | {', '.join(chosen) or expr} "
            f"| {'<br>'.join(c.replace('|', '/') for c in copyrights(package, texts))} |"
        )

    out = [BEGIN, "", "## Rust crates", ""]
    out.append(
        f"The {len(rows[True]) + len(rows[False])} crates (from Cargo.lock) that the packaged app is built from. "
        "Where a crate is offered under a choice of licences, \"Used under\" is the one Filo takes. "
        "Generated by `scripts/third-party-notices.py`; run it again when Cargo.lock changes."
    )
    for shipped, title, about in [
        (True, "Compiled into the app", "Their code is part of Filo's binary."),
        (False, "Used only to build it", "Build scripts, code generators and macros: they run while Filo is built, "
                                         "and none of their code is in the app."),
    ]:
        out += ["", f"### {title} ({len(rows[shipped])})", "", about, "",
                "| Crate | Version | Licence | Used under | Copyright |", "| --- | --- | --- | --- | --- |"]
        out += rows[shipped]
    out += ["", "### Licence texts", ""]
    missing = []
    for name in sorted(used, key=rank):
        text = license_text(name, pool) if name in FINGERPRINTS else None
        if text is None:
            missing.append(name)
            continue
        out += [f"#### {name}", "", "```", text, "```", ""]
    if missing:
        sys.exit(f"no licence text found for {', '.join(missing)}: add a fingerprint to FINGERPRINTS")
    out.append(END)
    return "\n".join(out) + "\n"


def main():
    with open(NOTICES, encoding="utf-8") as f:
        current = f.read()
    generated = generate()
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        new = head + generated + (("\n" + tail) if tail else "")
    else:
        new = current.rstrip("\n") + "\n\n" + generated
    if "--check" in sys.argv:
        if new != current:
            sys.exit("THIRD_PARTY_NOTICES.md is out of date: run python3 scripts/third-party-notices.py")
        return
    with open(NOTICES, "w", encoding="utf-8") as f:
        f.write(new)


if __name__ == "__main__":
    main()
